// All game text, in two languages: Russian and English.
//   * Loc.T("key") returns the string in the current language (an unknown key returns the key itself,
//     so a typo is visible in-game rather than blank).
//   * The language follows the phone: Russian when the OS language is Russian, English for every other
//     language. The player can switch it in Settings; that choice is saved and then wins over the OS.
//   * Loc.Art("key") picks language-specific art: in English it returns "key_en" when that picture exists
//     in the catalog, otherwise the base (Russian / neutral) picture.
public static class Loc
{
    public enum Lang { Ru, En }

    const string PrefKey = "Kuzya.Lang";      // "ru" / "en"; missing = follow the OS language
    static Lang? current;
    public static event Action Changed;

    public static Lang Current
    {
        get
        {
            if (current == null)
            {
                string saved = PlayerPrefs.GetString(PrefKey, "");
                if (saved == "ru") current = Lang.Ru;
                else if (saved == "en") current = Lang.En;
                else current = Application.systemLanguage == SystemLanguage.Russian ? Lang.Ru : Lang.En;
            }
            return current.Value;
        }
    }

    public static bool IsEnglish => Current == Lang.En;

    public static void Set(Lang lang)
    {
        if (current == lang && PlayerPrefs.HasKey(PrefKey)) return;
        current = lang;
        PlayerPrefs.SetString(PrefKey, lang == Lang.Ru ? "ru" : "en");
        PlayerPrefs.Save();
        Changed?.Invoke();
    }

    // English picture for a key when there is one ("ui_play_big" -> "ui_play_big_en")
    public static string Art(string key) => IsEnglish && GameArt.I.Has(key + "_en") ? key + "_en" : key;
    // true when the art for this key matches the current language (so a picture with Russian words is not shown in English)
    public static bool HasArt(string key) => IsEnglish ? GameArt.I.Has(key + "_en") : GameArt.I.Has(key);

